def _xuanlv(xiaojie):
    t, jieguo = 0.0, []
    for x in xiaojie:
        for p, d in x:
            jieguo.append((t, p, d))
            t += d
    return jieguo


def _hesheng(meixiaojie, biao):
    return {i * meixiaojie + pian: h for i, hs in enumerate(biao) for pian, h in hs}


